-- 로그인 시도 제한 — auth.mjs 설계 메모의 "방어선은 로그인 시도 제한과 계정 잠금"을 실제로 만든다.
--
-- 왜 지금인가: 관리자 화면이 생기면 그 계정 하나로 학원·학생 계정을 발급할 수 있다.
-- 6자리 PIN은 100만 가지뿐이라, 막지 않으면 스크립트로 몇 시간이면 다 넣어볼 수 있다.
-- (학생 PIN도 같은 위험이라 이 표는 모든 계정에 함께 적용한다.)
--
-- 잠그는 기준은 login_id 다. IP로 잠그면 공격자가 IP를 바꿔가며 피해 가고,
-- 학원처럼 여러 학생이 같은 공유기를 쓰는 곳에서는 애먼 학생이 같이 잠긴다.
-- 대신 남이 일부러 남의 아이디를 잠글 수 있으므로 잠금은 짧게 두고 단계적으로만 늘린다.
CREATE TABLE login_attempts (
    login_id     TEXT PRIMARY KEY,   -- 대문자로 정규화한 로그인ID (없는 계정도 기록 — 계정 존재 여부를 흘리지 않는다)
    fails        INTEGER NOT NULL DEFAULT 0,
    last_fail_at TEXT,
    locked_until TEXT                -- ISO 시각. 이 시각 전에는 PIN이 맞아도 거절
);
