-- 학부모용 PIN — 자녀 아이디 + 학부모용 PIN 으로 들어오는 방식(사용자 결정).
--
-- 왜 학생 행에 칸을 하나 더 두는가:
-- 학부모에게 별도 계정을 만들면 users 행이 두 배가 되고, "이 학부모가 이 아이의
-- 부모가 맞는가"를 잇는 표가 또 필요해진다. 아이 계정에 '부모용 열쇠'를 하나 더
-- 다는 편이 훨씬 단순하고, 개인정보 최소화 원칙(이메일·전화번호 없음)에도 맞다.
--
-- 두 열쇠는 서로 다른 문을 연다:
--   pin_hash        → 아이 앱 (문제를 푼다)
--   parent_pin_hash → 학부모 화면 (읽기만 한다)
-- 부모가 아이 PIN을 몰라도 되고, 아이가 부모 화면에 못 들어간다.
ALTER TABLE users ADD COLUMN parent_pin_hash TEXT;   -- NULL이면 아직 발급 안 함
